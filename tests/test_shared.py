"""Tests for System 2 Shared Infrastructure components S1 and S2.

Uses a small fixture dataset generated by System 1 in a tempdir so the tests
are fast and self-contained.
"""

from __future__ import annotations

import json
from pathlib import Path

import networkx as nx
import joblib
import numpy as np
import pandas as pd
import pytest

from src.system1_generator import g1_account_builder, g2_normal_generator, g3_scenario_injector, g4_splitter
from src.system1_generator.common import CONFIG_PATH, GeneratorConfig
from src.system2_detection.shared import s1_feature_engineering, s2_multigraph_builder
from src.system2_detection.shared.schemas import FEATURE_COLUMNS


@pytest.fixture(scope="session")
def shared_fixture(tmp_path_factory):
    """Generate a small dataset, then run S1 + S2 against it."""
    out_dir = tmp_path_factory.mktemp("shared-fixture")
    cfg = GeneratorConfig.from_file(CONFIG_PATH).override(
        num_accounts=400,
        num_historical_transactions=8_000,
        num_stream_transactions=2_000,
    )
    ctx = g1_account_builder.build_accounts(cfg)
    g1_account_builder.save_accounts(ctx)
    normal_df = g2_normal_generator.generate_normal(cfg, ctx)
    combined, suspicious, gt = g3_scenario_injector.inject_scenarios(cfg, ctx, normal_df)
    hist_df, stream_df = g4_splitter.split_and_export(combined, gt, out_dir=out_dir)

    historical_csv = out_dir / "historical_transactions.csv"
    artifact_dir = out_dir / "artifacts"

    # S1
    features, scaler = s1_feature_engineering.build_features(historical_csv=historical_csv)
    s1_feature_engineering.save_features(features, scaler, out_dir=artifact_dir)

    # S2 — uses accounts.parquet from data/internal which was written above
    G, node_idx, edge_idx = s2_multigraph_builder.build_multigraph(
        historical_csv=historical_csv, accounts_df=ctx.accounts
    )
    s2_multigraph_builder.save_artifacts(G, node_idx, edge_idx, out_dir=artifact_dir)

    return {
        "hist_df": hist_df,
        "features": features,
        "scaler": scaler,
        "graph": G,
        "node_index": node_idx,
        "edge_index": edge_idx,
        "artifact_dir": artifact_dir,
    }


