def test_s2_graph_is_multidigraph(shared_fixture):
    G = shared_fixture["graph"]
    assert isinstance(G, nx.MultiDiGraph)


def test_s2_edge_count_matches_transactions(shared_fixture):
    G = shared_fixture["graph"]
    hist_df = shared_fixture["hist_df"]
    assert G.number_of_edges() == len(hist_df)


def test_s2_multi_edges_preserved(shared_fixture):
    """For any pair (u,v) that appears multiple times in the data, the
    multigraph must have an edge per occurrence."""
    hist_df = shared_fixture["hist_df"]
    G = shared_fixture["graph"]
    # Find a pair with multiple transactions
    pair_counts = hist_df.groupby(["sender_account", "receiver_account"]).size()
    multi_pairs = pair_counts[pair_counts >= 2]
    assert not multi_pairs.empty, "fixture has no multi-edge pair to test"
    u, v = multi_pairs.index[0]
    expected = int(multi_pairs.iloc[0])
    assert G.number_of_edges(u, v) == expected, (
        f"({u},{v}) expected {expected} edges, got {G.number_of_edges(u, v)}"
    )


def test_s2_node_index_covers_all_accounts(shared_fixture):
    G = shared_fixture["graph"]
    node_index = shared_fixture["node_index"]
    assert set(node_index.keys()) == set(G.nodes())
    assert len(set(node_index.values())) == len(node_index), "node indices not unique"


def test_s2_edge_index_round_trip(shared_fixture):
    G = shared_fixture["graph"]
    edge_index = shared_fixture["edge_index"]
    hist_df = shared_fixture["hist_df"]
    assert set(edge_index.keys()) == set(hist_df["transaction_id"])
    # Spot check: every (u, v, key) tuple corresponds to a real edge in G
    sample = list(edge_index.items())[:200]
    for tx_id, triple in sample:
        u, v, key = triple
        assert G.has_edge(u, v, key=key), f"missing edge {u}->{v} key={key}"


def test_s2_node_attrs_populated_for_real_accounts(shared_fixture):
    G = shared_fixture["graph"]
    real_nodes = [n for n in G.nodes() if not str(n).startswith("EXT-")]
    assert real_nodes, "no real-account nodes found"
    # Check first 10 real nodes have non-null bank
    for n in real_nodes[:10]:
        attrs = G.nodes[n]
        assert attrs.get("bank") not in (None, ""), f"node {n} has no bank attr"


def test_s2_artifacts_persisted(shared_fixture):
    artifact_dir = shared_fixture["artifact_dir"]
    assert (artifact_dir / "transaction_multigraph.pkl").exists()
    assert (artifact_dir / "node_index.json").exists()
    assert (artifact_dir / "edge_index.json").exists()
    # node_index.json round-trip
    with open(artifact_dir / "node_index.json", "r", encoding="utf-8") as fh:
        ni = json.load(fh)
    assert ni == shared_fixture["node_index"]
